// Generates crates/pdf-crop/src/fonts/standard_data.rs: the metrics of the
// 14 standard PDF fonts and the standard single-byte encodings.
//
// The crop library needs the advance width of every glyph it walks past to
// know where the next glyph sits. Most fonts carry those widths in the PDF
// (/Widths, /W), but the 14 standard fonts may omit them: every reader has
// their metrics built in. This script turns that data into static Rust
// tables so the WebAssembly module has the same numbers.
//
// Sources:
// - widths and bounding boxes: Adobe's Core 14 AFM files, as bundled in
//   @pdf-lib/standard-fonts (MIT);
// - encodings (character code -> glyph name): ISO 32000-1 Annex D, from
//   scripts/encodings.json (transcribed from pdf.js, Apache-2.0; see its
//   "_source" entry).
//
// Run from the repository root after changing either source:
//   node crates/pdf-crop/scripts/generate-standard-metrics.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

const require = createRequire(import.meta.url);
const { Font, FontNames } = require("@pdf-lib/standard-fonts");

const here = import.meta.dirname;
const out = path.resolve(here, "../src/fonts/standard_data.rs");
const encodings = JSON.parse(
  readFileSync(path.resolve(here, "encodings.json"), "utf8"),
);

/** Built-in encoding of each font (the Latin ones use StandardEncoding). */
const BUILTIN = { Symbol: "Symbol", ZapfDingbats: "ZapfDingbats" };

const fonts = Object.values(FontNames).map((name) => {
  const afm = Font.load(name);
  // Byte order (not locale order), so Rust can binary search by &[u8].
  const widths = afm.CharMetrics.map((m) => [m.N, m.WX]).sort(([a], [b]) =>
    Buffer.compare(Buffer.from(a), Buffer.from(b)),
  );
  return {
    name,
    bbox: afm.FontBBox,
    widths,
    builtin: BUILTIN[name] ?? "StandardEncoding",
  };
});

const rustString = (s) => JSON.stringify(s);
const encodingTable = (key) => `[${encodings[key].map(rustString).join(", ")}]`;
const encodingConst = (constName, key) =>
  `/// ${key}: glyph name by character code ("" = undefined).\n` +
  `pub static ${constName}: [&str; 256] = ${encodingTable(key)};\n`;

const rust = `// @generated by crates/pdf-crop/scripts/generate-standard-metrics.mjs. Do not edit.
// Widths and bounding boxes: Adobe Core 14 AFM metrics via
// @pdf-lib/standard-fonts (MIT). Encodings: ISO 32000-1 Annex D, transcribed
// from pdf.js (Copyright 2012 Mozilla Foundation, Apache License 2.0).

/// Metrics of one of the 14 standard PDF fonts.
pub struct StandardFontData {
    /// PostScript name, e.g. \`Helvetica-Bold\`.
    pub name: &'static str,
    /// Font bounding box in glyph units (1/1000 em): llx, lly, urx, ury.
    pub bbox: [i16; 4],
    /// Advance widths by glyph name, sorted by name bytes.
    pub widths: &'static [(&'static str, u16)],
    /// The font's built-in encoding (glyph name by code).
    pub builtin: &'static [&'static str; 256],
}

${encodingConst("STANDARD_ENCODING", "StandardEncoding")}
${encodingConst("MAC_ROMAN_ENCODING", "MacRomanEncoding")}
${encodingConst("WIN_ANSI_ENCODING", "WinAnsiEncoding")}
${encodingConst("SYMBOL_ENCODING", "Symbol")}
${encodingConst("ZAPF_DINGBATS_ENCODING", "ZapfDingbats")}
/// The 14 standard fonts.
pub static STANDARD_FONTS: [StandardFontData; ${fonts.length}] = [
${fonts
  .map(
    (f) => `    StandardFontData {
        name: ${rustString(f.name)},
        bbox: [${f.bbox.join(", ")}],
        widths: &[${f.widths.map(([n, w]) => `(${rustString(n)}, ${w})`).join(", ")}],
        builtin: &${
          {
            StandardEncoding: "STANDARD_ENCODING",
            Symbol: "SYMBOL_ENCODING",
            ZapfDingbats: "ZAPF_DINGBATS_ENCODING",
          }[f.builtin]
        },
    },`,
  )
  .join("\n")}
];
`;

writeFileSync(out, rust);
console.log(`wrote ${path.relative(process.cwd(), out)}`);
