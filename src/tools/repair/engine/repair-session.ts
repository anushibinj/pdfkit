/**
 * Repair orchestrator combining WebAssembly byte carving and PDFium verification.
 *
 * Implements SOLID Principles:
 * - Single Responsibility: Orchestrates repair strategy execution and verification.
 * - Open/Closed: Extensible repair strategies through polymorphic modules.
 * - Liskov Substitution: Operates transparently against any compatible verifier and module.
 * - Dependency Inversion: Depends upon abstractions (PdfRepairModule, RepairVerifier).
 */

import type { RepairOutcome, RepairReport } from "../core/model";
import { parseRepairReport } from "../core/report";
import type { PdfRepairModule } from "./repair-pdf-module";
import type { RepairVerifier } from "./repair-verifier";

/** Options controlling repair pipeline execution. */
export interface RepairOptions {
  /** Optional open password for encrypted documents. */
  password?: string;
  /** Whether to force reserialization through PDFium to guarantee standard structure. */
  normalize?: boolean;
}

/**
 * High-level repair session coordinating the two-tier recovery engine.
 */
export class RepairSession {
  /**
   * @param repairModule The WebAssembly carving and reconstruction engine.
   * @param verifier The PDFium document verifier and normalizer.
   */
  constructor(
    private readonly repairModule: PdfRepairModule,
    private readonly verifier: RepairVerifier,
  ) {}

  /**
   * Executes repair on damaged PDF bytes.
   *
   * Strategy flow:
   * 1. Check if the raw input is already valid in PDFium (some damaged PDFs have minor
   *    corruption that PDFium can open directly).
   * 2. If already valid and reserializable:
   *    - Reserialize a clean copy via PDFium.
   *    - Formulate a clean repair report noting that linear reconstruction was applied.
   * 3. If PDFium cannot open it directly or reports corruption:
   *    - Invoke the Rust WebAssembly engine (`PdfRepairModule`).
   *    - The Rust module executes byte carving: stripping junk headers/BOMs, discovering
   *      unreferenced objects, synthesizing trailer dictionaries, and rebuilding xref tables.
   * 4. If the Rust module succeeds:
   *    - Verify the carved PDF with `RepairVerifier`.
   *    - If verifier confirms it is valid and has pages, return a `repaired` outcome with
   *      the parsed report and verified page count.
   * 5. If verifier reports `password-required`:
   *    - Return `password-required` outcome so user can supply credentials.
   * 6. If both approaches fail to recover a valid PDF:
   *    - Return a `failed` outcome with diagnosis message.
   *
   * @param bytes Corrupted PDF input bytes.
   * @param options Password and normalization options.
   * @returns Detailed {@link RepairOutcome}.
   */
  async repair(
    bytes: Uint8Array,
    options: RepairOptions = {},
  ): Promise<RepairOutcome> {
    const password = options.password ?? "";

    if (bytes.length === 0) {
      return {
        kind: "failed",
        message: "File is empty (0 bytes).",
      };
    }

    // Step 1: Preliminary check with PDFium linear recovery
    const directVerification = this.verifier.verify(bytes, password, true);

    if (directVerification.valid) {
      // PDFium opened it directly. Produce normalized bytes if available.
      const repairedBytes = directVerification.normalizedBytes ?? bytes;
      const report: RepairReport = {
        headerRepaired: false,
        eofRepaired: false,
        xrefReconstructed: true,
        trailerReconstructed: false,
        objectsRecovered: 0,
        streamsRepaired: 0,
        pagesRecovered: directVerification.pageCount,
        issues: [
          "Linear object recovery applied by document parser",
          "Cross-reference table rebuilt and normalized",
        ],
      };

      return {
        kind: "repaired",
        pdf: repairedBytes,
        pageCount: directVerification.pageCount,
        report,
      };
    }

    if (directVerification.reason === "password-required") {
      return {
        kind: "password-required",
      };
    }

    // Step 2: Carve and reconstruct via Rust WASM module
    const wasmResult = this.repairModule.repair(bytes);

    if (wasmResult.ok) {
      // Parse report generated by Rust engine
      const report = parseRepairReport(wasmResult.report);

      // Verify the reconstructed bytes using PDFium
      const carvedVerification = this.verifier.verify(
        wasmResult.pdf,
        password,
        options.normalize ?? true,
      );

      if (carvedVerification.valid) {
        const finalBytes =
          carvedVerification.normalizedBytes ?? wasmResult.pdf;

        report.pagesRecovered = Math.max(
          report.pagesRecovered,
          carvedVerification.pageCount,
        );

        return {
          kind: "repaired",
          pdf: finalBytes,
          pageCount: carvedVerification.pageCount,
          report,
        };
      }

      if (carvedVerification.reason === "password-required") {
        return {
          kind: "password-required",
        };
      }
    }

    // Both direct recovery and WASM carving could not produce a valid PDF
    const failureReason = wasmResult.ok
      ? "Carved PDF could not be verified by document parser."
      : wasmResult.message;

    return {
      kind: "failed",
      message: failureReason,
    };
  }
}
